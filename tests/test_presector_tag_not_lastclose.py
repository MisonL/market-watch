#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""「关注板块（参考价=昨收）」+ 一串非零涨跌幅 —— 自相矛盾，且语义是错的。

## 实测（2026-11-25 09:24 真实推送）

    **关注板块**（参考价=昨收）
    半导体 -2.56%
    存储芯片 -2.58%
    CPO概念 -3.07%
    …

若参考价真是昨收，涨跌幅只可能是 `+0.00%`（指数段就是这样：f3=0、
点位=昨收，那里写「参考价=昨收」是对的）。而板块这里是一串当日方向数字。

全量核对 25 个交易日（每天 8 个板块）：

| 对比对象 | 吻合/可比 |
|---|---|
| 盘前值 vs **前一日收盘涨跌幅** | **0/8**（从无一天吻合） |
| 盘前值 vs **开盘后第一帧** | 7~8/8 **同向**、量级连续 |

    [实例] 11-25 盘前 半导体 -2.56%，09:37 -2.97%；
           11-24 收盘 +1.08% —— 盘前若是昨收，不可能 -2.56%。

结论：盘前板块涨跌幅是**集合竞价参考价相对昨收**的变动。

## 危害

不是"措辞不精确"：
· 读者会把当日竞价方向读成"昨天的行情"（-2.56% 当成昨日跌幅）；
· 或反过来把竞价参考价当成"已经成交出来的跌幅"（还没开盘就有成交）；
· 两种误读都会影响当天决策，而同一段数字本身是对的 —— 只有这句话错。

## 修法（两层）

· **机制**：`_fix_presector_tag()` —— 段头声称「昨收」且段内**有非零
  涨跌幅**时改成「（涨跌幅相对昨收）」。判据落在数据自身，不靠 prompt。
  段内全是 `+0.00%`/`平盘` 时**不动**（那时「=昨收」是对的）。
· **prompt**：规则⑥ 里明写盘前涨跌幅的语义与「不要写 =昨收」。

⚠️ 两处**与实测相反**的注释也一并改正（`_chg_board` 与兜底模板）——
「盘前它就是上一交易日的涨跌幅」这句话是这条缺陷的温床：
读注释的人会照着它写文案。

## 本文件锁住什么

① 今日真实形态被改写
② 全平盘 / 全 +0.00% 时**保留**原句（不能矫枉过正 —— 那时它是对的）
③ 段头没声称「昨收」时不动
④ 【指数】/【盘面】段里的「参考价=昨收」**不得**被改（那里是对的）
⑤ 全角「＝」也认
⑥ 极小值（-0.001%）按平盘处理，不改写
⑦ 幂等：跑两遍与一遍结果相同
⑧ 接线：`produce_text` 收尾管线里真的调了它，且排在 `_norm_sectors` 之后
⑨ 真实推送回归：今天 09:24 那条过一遍管线后不再自相矛盾
⑩ 注释不得再出现「盘前它就是上一交易日的涨跌幅」这句错话
"""
import datetime as _dt
import json
import os
import re
import sys
import tempfile

os.environ.setdefault("MW_DIR", tempfile.mkdtemp(prefix="mw_t_presector_"))

_HERE = os.path.dirname(os.path.abspath(__file__))
_SRC = os.path.join(_HERE, "..", "src")
sys.path.insert(0, _SRC)

import analyze as A

_ok = 0


def check(cond, msg):
    global _ok
    if cond:
        _ok += 1
    else:
        print(f"  ❌ {msg}")
        sys.exit(1)


_F = A._fix_presector_tag

# ---------- ① 今日真实形态 ----------
_REAL = ("**关注板块**（参考价=昨收）\n"
         "半导体 -2.56%\n存储芯片 -2.58%\nCPO概念 -3.07%\n")
_o = _F(_REAL)
# ⚠️ 判据不能写「没有『昨收』二字」—— 正确的新段头是
# 「（涨跌幅相对昨收）」，它本来就要提到昨收（那是**基准**）。
# 要拦的是把昨收说成**参考价本身**（`参考价=昨收`）。
check("参考价" not in _o.split("\n")[0],
      f"段头仍把昨收说成参考价：{_o.split(chr(10))[0]!r}")
check("涨跌幅相对昨收" in _o.split("\n")[0],
      f"段头没改成「涨跌幅相对昨收」：{_o.split(chr(10))[0]!r}")
check("半导体 -2.56%" in _o, "改段头时把板块行也动了")

# ---------- ② 不能矫枉过正：全平盘时那句话是对的 ----------
for _t in ("**关注板块**（参考价=昨收）\n半导体 平盘（0 亿）",
           "**关注板块**（参考价=昨收）\n半导体 +0.00%（0 亿）",
           "**关注板块**（参考价=昨收）\n半导体 平盘\n白酒 平盘"):
    check(_F(_t) == _t,
          f"段内全是 0.00/平盘时不该改写（那时「=昨收」是对的）："
          f"{_F(_t)!r}")

# ---------- ③ 段头没声称「昨收」→ 不动 ----------
_t3 = "**关注板块**\n半导体 -2.56%\n"
check(_F(_t3) == _t3, f"没声称昨收却改了：{_F(_t3)!r}")

# ---------- ④ 【指数】/【盘面】里的「参考价=昨收」不得被改 ----------
for _t in ("**盘面**（参考价=昨收）\n半导体 -2.56%",
           "**指数**（参考价=昨收）\n上证指数 3548.10",
           "**关键位**（参考价=昨收）\n半导体 -2.56%"):
    check(_F(_t) == _t,
          f"改了非「关注板块」段头 —— 【指数】那里写昨收是**对的**"
          f"（f3=0、点位就是昨收）：{_F(_t)!r}")

# ---------- ⑤ 全角等号 ----------
_t5 = "> **关注板块**（参考价＝昨收）\n半导体 -1.00%\n"
_o5 = _F(_t5)
check("参考价" not in _o5.split("\n")[0] and "涨跌幅相对昨收" in _o5,
      f"全角「＝」形态没认出来：{_o5.split(chr(10))[0]!r}")

# ---------- ⑥ 极小值按平盘 ----------
_t6 = "**关注板块**（参考价=昨收）\n半导体 -0.001%\n"
check(_F(_t6) == _t6, f"|x|<0.005 应视为平盘、不改写：{_F(_t6)!r}")

# ---------- ⑦ 幂等 ----------
_once = _F(_REAL)
check(_F(_once) == _once, f"不幂等：第二遍又改了：{_F(_once)!r}")

# ---------- ⑧ 接线 ----------
_src = open(os.path.join(_SRC, "analyze.py"), encoding="utf-8").read()
check("txt = _fix_presector_tag(txt)" in _src,
      "收尾管线里没有调用 `_fix_presector_tag` —— 函数写了但没接线")
_i_norm = _src.find("    txt = _norm_sectors(txt)\n")
_i_fix = _src.find("    txt = _fix_presector_tag(txt)\n")
check(0 < _i_norm < _i_fix,
      f"`_fix_presector_tag` 应排在 `_norm_sectors` **之后**"
      f"（板块行先被统一形态，判「有没有非零涨跌幅」才可靠）；"
      f"实际 norm={_i_norm} fix={_i_fix}")

# ---------- ⑨ 真实推送回归 ----------
_pushes = os.path.join(_HERE, "..", "state", "history", "pushes.jsonl")
if os.path.exists(_pushes):
    _rows = [json.loads(l) for l in open(_pushes, encoding="utf-8")]
    _hit = [r for r in _rows
            if str(r.get("t", "")).startswith("2026-11-25 09:24")]
    check(bool(_hit), "找不到 2026-11-25 09:24 那条推送（数据变了？）")
    _raw = str(_hit[0].get("text") or "")
    check("参考价=昨收" in _raw,
          "那条推送里已经没有「参考价=昨收」—— 本用例的前提变了，请重新取证")
    _fixed = _F(_raw)
    _hdr = [ln for ln in _fixed.split("\n") if "关注板块" in ln]
    check(bool(_hdr) and "参考价" not in _hdr[0],
          f"真实推送过一遍后段头仍自相矛盾：{_hdr[:1]!r}")
    # 正文其余部分一个字节都不许动
    _a = _raw.replace("**关注板块**（参考价=昨收）", "")
    _b = _fixed.replace(_hdr[0], "")
    check(len(_fixed) - len(_raw) == len(_hdr[0]) - len(
              [ln for ln in _raw.split("\n") if "关注板块" in ln][0]),
          "改写动到了段头以外的正文")

# ---------- ⑩ 注释不得再写那句与实测相反的话 ----------
_code = re.sub(r"^\s*#.*$", "", _src, flags=re.M)   # 去掉注释行再做断言
for _bad in ("盘前它就是上一交易日的涨跌幅",
             "这些涨跌幅是**上一交易日**的"):
    check(_bad not in _src,
          f"注释里仍写着与实测相反的话：{_bad!r} —— "
          f"读注释的人会照着它写文案（这条缺陷就是这么来的）")

print(f"ALL PASS (盘前板块涨跌幅不是昨收，段头不得自相矛盾 {_ok} 个断言)")
