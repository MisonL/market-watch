"""金额闸门：约数助词与无单位裸数字 —— 2026-11-08 复核。

## 缺陷（两条都是先天存在，不是本轮改动引入）

`safe()` 的 `AMT_RE` 用「数字必须紧贴单位/货币符号」这个**结构性假设**
识别个人金额。而人写钱数时恰好有四种形态绕开它：

```
'账上还有三百多万没动'   → 放行   （约数助词「多」打断 [_CN_NUM]{1,6}）
'二十余万的备用金'       → 放行   （「余」同上）
'五十几万' / '百把万'     → 放行   （「几」「把」同上）
'账上还剩12000'          → 放行   （无单位裸数字，七个正则全 None）
'￥5000' / '＄5000'      → 放行   （全角货币符号）← 已单独修
```

第二条之所以能拦 `'账户还剩12000'`，**只是因为「账户」恰好在 `BANNED` 里**；
换成「账上」就漏了 —— 这是词表碰巧覆盖，不是判据正确。

## 修法

1. **约数助词**：`[_CN_NUM]{1,6}` 后面允许夹**一个** `多/来/余/几/把/数`。
   只允许一个 —— 两个以上连续助词不成词，放宽只会增误拦。
2. **裸数字**：`_bare_amt_hit()` —— 个人口径词 + 16 字内（**同一子句**）的
   4 位以上裸数字。
   - 4 位：指数点位/板块价位几乎都在 3 位以下（站上 4200 / 跌破 380），
     与个人金额在量级上自然分开。
   - 后接「亿/万」排除：那是市场口径。
   - 市场限定语排除：融资余额/两融/北向/存款准备金 不是「我们的钱」。
   - 遇到句读就停：`'余额不足。成交额 12500 亿'` 不得误判。

## 一个必须记住的正则陷阱

`\\d{4,}(?![\\d.])` 里那个 `(?![\\d.])` 不能省。没有它时 `\\d{4,}` 会
**回溯到更短的前缀**：

```
'余额 12000 亿元'
  贪心匹配「12000」→ 后接「亿」被 (?!\\s*[亿万]) 否掉
  → 回溯到「1200」→ 后一位是「0」，不是亿/万 → 通过 ❌
```

加上 `(?![\\d.])` 后，回溯到「1200」时后一位是数字 → 否掉 → 整条不命中。

跑法：`MW_DIR=$(mktemp -d) python3 tests/test_amount_gate_forms.py`
"""
import os, sys, tempfile, atexit, shutil

if "MW_DIR" not in os.environ:
    _td = tempfile.mkdtemp(prefix="mw_t_")
    os.environ["MW_DIR"] = _td
    atexit.register(shutil.rmtree, _td, ignore_errors=True)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "src"))

import marketlib as M

# 必须拦下：个人金额的各种自然写法
_LEAK = [
    # 繁体（2026-11-09）：BANNED 只给「仓」族补了繁体，
    # 萬/塊/帳/淨/賺/虧 全漏…——归一在 _mask() 入口
    "賺了 8 萬",
    "虧了三百多萬",
    "現金 3 萬",
    "留 5000 塊",
    "帳上還有 12000",
    "賬上還有 12000",
    # 约数助词
    "账上还有三百多万没动",
    "这部分资金还剩一百多万，可以慢慢加",
    "二十余万的备用金",
    "大概五十几万的样子",
    "百把万现金",
    "十万来块",
    "三数万元",
    # 无单位裸数字
    "账上还剩12000",
    "卡里还有 35000",
    "余额只剩 5000",
    # 全角货币符号（中文输入法默认形态）
    "￥5000",
    "＄5000",
    "￥ 5000",
    # 单位被括号/引号包住（2026-11-08 补）：AI 带 markdown 装饰时就是这个形态
    "另留 5000【元】备用",
    "留 5000「元」备用",
    "留 5000(元)备用",
    "留 5000【万元】备用",
    "留 5000（万）",
]

# 必须放行：市场口径，误拦会让整条播报被打回重写
_OK = [
    # 市场口径，带繁体不得被当成私人金额
    "台灣中央銀行決定升息",
    "成交额 1.2 万亿",
    "两市成交额 12000 亿元",
    "主力净流入 28.31 亿",
    "净流入 42 亿",
    "市值 3800 亿",
    "融资余额增至 1.79 万亿",
    "余额 12000 亿元",
    "存款准备金 12000 亿",
    "余额宝规模 1.5 万亿",
    "余额不足。成交额 12500 亿",
    "站上 4200",
    "失守 3800 点",
    "跌破 3800 点",
    "涨幅 3.5%",
    # 括号包住的**板块名**不得被当成金额（与旧有的元件/元宇宙同类）
    "【半导体】元件涨价",
    "【板块】元件",
    "排名第三元件",
]


def check():
    _bad = []
    for _s in _LEAK:
        _ok, _hit = M.safe(_s)
        if _ok:
            _bad.append(f"漏拦：{_s!r}")
    assert not _bad, "个人金额写法未被拦下：\n  " + "\n  ".join(_bad)

    _bad = []
    for _s in _OK:
        _ok, _hit = M.safe(_s)
        if not _ok:
            _bad.append(f"误拦：{_s!r} -> hit={_hit!r}")
    assert not _bad, "市场口径被误拦：\n  " + "\n  ".join(_bad)

    # 正则会话：数字尾巴必须管住，否则「12000 亿」会回溯成「1200」而漏网
    assert M._bare_amt_hit("余额 12000 亿元") is None, (
        "「余额 12000 亿元」必须放行 —— 这是市场口径（后的「亿」）")
    assert M._bare_amt_hit("账上还剩 12000") is not None, (
        "「账上还剩 12000」必须命中 —— 这是无单位裸数字的个人金额")

    print(f"ALL PASS (金额闸门 {len(_LEAK) + len(_OK) + 2} 个断言)")


if __name__ == "__main__":
    check()
