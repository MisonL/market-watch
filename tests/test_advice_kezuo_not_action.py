#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""「可作防御方向」不是指令 —— 把它当指令会**删掉主语**。

## 实测

真实推送里含 `可作` 的 **9 条**，全部是同一类形态：

    09-30 「创新药、白酒、消费风格价量齐升，**可作防御方向**」
    10-22 「白酒、消费风格跌幅最小，**可作防御观察**」
    10-29 「若放量止跌**可作为观察点**」
    11-13 「属防御性承接，**可作为观察方向**」
    11-17 「消费风格逆势收红**可作防御参考**」

**没有一条是"叫你去买/卖"** —— 它们说的是「A 可以当成 B」，是**判断连词**，
与已经被豁免的 `可关注资金是否…`（观察条件）同一类。

## 后果不是少一句话，是删掉主语

`_advice_trim_line` 只删命中指令的**那个分句**，其余逐字保留。于是：

    IN : > 机会 创新药可作观察方向，主力占比+3.1%
    OUT: > 机会 主力占比+3.1%

「创新药」三个字连根删掉，读者看到一个**没有主语的数字** ——
比原句更危险，因为原句至少说清了是哪个板块。

这是本仓库反复修的「拆东墙」：为了堵一个并不存在的指令，
把必须保留的事实（主语）一起删了。

## 本文件锁住什么

① `可作 / 可当 / 可视为` 不算指令（判断连词，与 `可关注` 同类）
② `可跟踪 / 可介入 / 可参与 / 可低吸 / 可抄底 / 可加仓` **仍算**指令
   （那些真的是"可以买"）
③ `不宜追 / 追高 / 抢反弹 / 接飞刀` 仍算
④ `减仓 / 加仓` 那族（`_ADVICE_ACT`）不受影响
⑤ **行为级**：`可作` 行的主语必须还在输出里
⑥ 反向：真指令行的动作分句必须真的被删掉（不能一刀切全放过）
"""
import os
import sys
import tempfile

os.environ.setdefault("MW_DIR", tempfile.mkdtemp(prefix="mw_t_kezuo_"))

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "src"))

import analyze as A

_ok = 0


def check(cond, msg):
    global _ok
    if cond:
        _ok += 1
    else:
        print(f"  ❌ {msg}")
        sys.exit(1)


# ---------- ① 判断连词不算指令 ----------
# 全部取自真实推送原文（state/history/pushes.jsonl）
_JUDGE = [
    "> 机会 创新药、白酒、消费风格价量齐升，可作防御方向",
    "> 机会 白酒、消费风格跌幅最小，可作防御观察",
    "> 机会 若放量止跌可作为观察点",
    "> 机会 属防御性承接，可作为观察方向",
    "> 机会 消费风格逆势收红可作防御参考",
    "> 机会 半导体设备有主力净流入，可作为低位替补方向",
    "> 机会 游戏与医药流通有主力吸筹，可作防守方向关注",
    "可当作反例",
    "可视为已确认",
]
for _t in _JUDGE:
    _h = A._advice_hit(_t)
    check(_h is None,
          f"`可作/可当/可视为` 仍被判成交易指令（命中 {_h!r}）：{_t}\n"
          f"      它们是判断连词（「A 可以当成 B」），与已豁免的 `可关注` 同类；"
          f"真实的 9 条推送里没有一条是叫读者买卖")

# ---------- ② 真正的"可以买"仍必须拦住 ----------
_BUY = {
    "可跟踪": "> 机会 CPO 可跟踪",
    "可介入": "> 机会 半导体可介入",
    "可参与": "> 机会 机器人链可参与",
    "可低吸": "> 机会 若回踩 20 日线可低吸",
    "可抄底": "> 机会 超跌方向可抄底",
    "可加仓": "> 机会 主力回流可加仓",
}
for _w, _t in _BUY.items():
    _h = A._advice_hit(_t)
    check(_h == _w,
          f"{_w!r} 应被判成指令（命中 {_w!r}），实得 {_h!r}：{_t}")

# ---------- ③ 冲进去那族 ----------
for _w, _t in (("不宜追", "不宜追高"),
               ("追高", "半导体已追高"),
               ("抢反弹", "不建议抢反弹"),
               ("接飞刀", "不接飞刀")):
    check(A._advice_hit(_t) is not None,
          f"{_w!r} 应被判成指令：{_t}")

# ---------- ③b `不接力` 是事实，不是"别买" ----------
# `[实测]` 真实推送 2 条被误判（10-14 13:36「A股午后不接力」、
# 10-20 11:44「午后资金不接力则逢高减」）—— `不接` 是**纯子串匹配**，
# `不接力` 一样命中。而「资金不接力」说的是资金没跟上（事实），
# 与「反弹不接」（别买）完全是两件事。
for _t in ("**盘面** A股午后不接力：创业板指 -1.80%",
           "> 风险 午后资金不接力则逢高减"):
    check(A._advice_hit(_t) is None,
          f"`不接力`（资金没跟上，是事实）被当成「别买」了"
          f"（命中 {A._advice_hit(_t)!r}）：{_t}")
# 反向：真的"别买"仍要拦
for _t in ("> 风险 反弹不接；半导体走弱", "> 风险 暂不接。",
           "> 风险 不接下跌中的品种"):
    check(A._advice_hit(_t) is not None,
          f"真正的「不接」（别买）没被拦下：{_t}")
# 行为级：不接力那行必须**逐字保留**
_o = A._advice_trim_line("> 风险 午后资金不接力则逢高减")
check(_o is not None and "不接力" in _o,
      f"「不接力」那行被降级/删改了：{_o!r}")

# ---------- ④ 减仓/加仓那族不受影响 ----------
for _t in ("> 风险 反弹无量宜减仓", "明日开盘减一半", "建议逢反弹分批减仓"):
    check(A._advice_hit(_t) is not None,
          f"动作词族失效了：{_t!r} 没被拦下")

# ---------- ⑤ 行为级：主语必须还在 ----------
_txt = "> 机会 创新药可作观察方向，主力占比+3.1%"
_out = A._advice_trim_line(_txt)
check(_out is not None, f"`_advice_trim_line` 对 `可作` 行返回 None（被整行降级）：{_txt}")
check("创新药" in (_out or ""),
      f"「可作」行降级后**主语被删掉了**：{_out!r}\n"
      f"      读者看到一个没有主语的数字（原行：{_txt}）")
check("主力占比+3.1%" in (_out or ""),
      f"「可作」行降级后事实分句丢了：{_out!r}")

# 多个真实形态一起验
for _t in ("... 白酒、消费风格跌幅最小，可作防御观察",
           "消费风格逆势收红可作防御参考"):
    _o = A._advice_trim_line("> 机会 " + _t)
    check(_o is not None and ("白酒" in _o or "消费风格" in _o),
          f"「可作」行降级后主语丢了：{_o!r}")

# ---------- ⑥ 反向：真指令行必须真的被删 ----------
_txt2 = "> 风险 半导体已追高，主力净流出 8 亿"
_out2 = A._advice_trim_line(_txt2)
check(_out2 is not None and "追高" not in _out2,
      f"真指令行没被处理 —— `追高` 还在：{_out2!r}")
check("主力净流出 8 亿" in (_out2 or ""),
      f"删指令时把同行的**事实**一起删了（拆东墙）：{_out2!r}")

# ---------- ⑦ 正则本身不含「可作/可当/可视为」这族 ----------
_pat = A._ADVICE_ACT_SHAPE.pattern
check("可(?:跟踪|介入|参与|低吸|抄底|加仓)" in _pat,
      f"`可(跟踪|介入|…)` 这族在正则里找不到：{_pat!r}")
for _w in ("作", "当", "视为"):
    check(f"|{_w})" not in _pat and f"|{_w}|" not in _pat,
          f"正则里仍有 `可…{_w}` 这一支（判断连词被当成指令）：{_pat!r}")

print(f"ALL PASS (可作不是指令 · 主语不得被删 {_ok} 个断言)")
