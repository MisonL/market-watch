#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""「贵金属主力+7389万」是板块资金，不是发送者自己的钱。

## 实测漏报

`[实测]` 2026-11-23 09:38:34 生产日志：

    BLOCKED hit='7389万' :: '> **触发提醒 · 印制电路板走强** …
      **触发** 恒生科技3465.44≤3482.43；贵金属主力+7389万(占+9.0%)；…'

`state/history/pushes.jsonl` 里对应记录 `ok=False, note=hit=7389万` ——
**整条触发提醒没有发出**。那是当天早盘唯一一条异动播报。

## 为什么偏偏是「万」

`AMT_RE` 的「亿」量级被 `(?!亿)` 排除（亿太小写不出个人金额），
只有「万/千/元/块」进闸门。`主力+3亿`、`主力+5亿` 都放行（实测），
而 `7389万` 落在 <1 亿 —— 正好是小市值板块的主力流入量级。

## 修法

`_AMT_CTX`（同子句语境词）补 `主力 / 游资 / 机构席位`。

## 为什么不会放过个人金额（本文件的核心守卫）

豁免**要求语境词与该金额同子句**（`_AMT_BREAK` 切分），
且 `PRON_RE` 是**独立的一道闸** —— 带「我/我们/你」的口径照样拦：

    safe('我主力买了5万')    -> 拦（「我」被 PRON_RE 抓）
    safe('我留了 5万 备用')  -> 拦
    safe('另有 7389万 房产') -> 拦（没有「主力」，语境词不成立）

⚠️ 这一类修改**必须双向验**：只验"板块资金放行了"会让闸门形同虚设，
只验"个人金额仍拦"则看不出漏报已修。第一版只加词不验反向，
跑不出任何信号。
"""
import os
import sys
import tempfile

os.environ.setdefault("MW_DIR", tempfile.mkdtemp(prefix="mw_t_zhuli_"))

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "src"))

import marketlib as M

_ok = 0


def check(cond, msg):
    global _ok
    if cond:
        _ok += 1
    else:
        print(f"  ❌ {msg}")
        sys.exit(1)


# ---------- ① 板块资金必须放行 ----------
_ALLOW = (
    "贵金属主力+7389万(占+9.0%)",          # 2026-11-23 实际被拦的那条
    "板块主力+7389万",
    "主力 7389万",
    "主力净流入 7389万",
    "机构席位买入 7389万",
    "游资 7389万",
)
for _t in _ALLOW:
    _safe, _hit = M.safe(_t)
    check(_safe is True,
          f"板块资金被当成个人金额拦下（命中 {_hit!r}）：{_t}\n"
          f"      `[实测]` 2026-11-23 09:38 就是这么漏掉整条触发提醒的")

# ---------- ② 个人金额必须仍被拦 ----------
_BLOCK = (
    ("我留了 5万 备用", "我"),
    ("我主力买了5万", "我"),
    ("另有 7389万 房产", "7389万"),
    ("个人持仓 5万", "持仓"),
    ("我的账户有7389万", "我的"),
    ("我打算买 7000万", "7000万"),
)
for _t, _why in _BLOCK:
    _safe, _hit = M.safe(_t)
    check(_safe is False,
          f"个人金额没被拦下 —— 闸门被放宽过头了：{_t}（为什么应拦：{_why}）")

# ---------- ③ 跨子句不得豁免（语境词必须同子句）----------
# 「主力流入」在上一句、个人金额在下一句 —— 不能借上一句的语境词放行。
_cross = "半导体主力流入 3亿。另留 7389万 备用。"
_ok3, _hit3 = M.safe(_cross)
check(_ok3 is False,
      f"跨子句借语境词放行了个金额：{_cross}（命中 {_hit3!r}）")

# ---------- ④ 「亿」量级本来就不进闸门（记录现状，防有人改了 (?!亿)）----------
# ⚠️ 用**静态**断言钉 `(?!亿)`：行为断言在这里没有判别力 ——
# 即使把 `(?!亿)` 删掉，`主力` 已在语境词表里，`主力+3亿` 仍会放行
# （实测：注入"删掉 (?!亿)"后 19 条全绿，等于没测）。
# 真正该守住的是"亿不进闸门"这个**机制**本身。
_amt = M.AMT_RE.pattern
# ⚠️ 只判"(?!亿) 在不在"**没有判别力**：AMT_RE 里有 4 处 `(?!亿)`，
# 只删其中一处不会变红（实测确认）。必须钉**「主力+7389万」实际走的那一支**
# —— 就是「万/千元/千」后面紧跟 `(?!亿)(?![_AMT_COMPOUND])` 的那条。
check('(?:万元|万|千元|千))(?!亿)(?![' in _amt,
      f"AMT_RE 的「万」分支丢了 `(?!亿)` —— 「亿」量级将进入个人金额闸门"
      f"（主力+7389万 正是走这一支）：{_amt[:160]!r}")
for _t in ("主力+3亿", "印制电路板主力-4.56亿"):
    _safe, _hit = M.safe(_t)
    check(_safe is True,
          f"「亿」量级的板块资金被拦了：{_t}（命中 {_hit!r}）")

# ---------- ⑤ 词表里真的写着这三个词 ----------
_ctx = M._AMT_CTX.pattern
for _w in ("主力", "游资", "机构席位"):
    check(_w in _ctx,
          f"`_AMT_CTX` 里没有 {_w!r} —— 同类漏报会复现")

print(f"ALL PASS (板块主力资金不得当成个人金额 {_ok} 个断言)")
