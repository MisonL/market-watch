#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""长段拆行时，硬切**绝不能把数字和它的单位劈到两行**。

## 为什么（2026-11-24 生产实据，用户第一眼就发现了）

当日 10:00 槽位的播报里出现这么两行：

    **关键位** …科创50 距 20 日低 +12.35
      %，为各指数中最远；创业板指距 20 日高 -12.19%…

百分号被甩到下一行行首，成了一句话都读不通的残句。用户的原话是「怎么乱了呀」。

根因在 `_split_wall_lines` 的**硬切**分支：它的守卫只有

    while (_cut > 10 and _p[_cut:_cut + 1].isdigit()):
        _cut -= 1

`isdigit()` 挡得住"切在数字**前面**"，但**完全挡不住"切在单位前面"** ——
`"12.35"` 和 `"%"` 之间看着是同一串字符，切在这里不触发任何检查。

而且这不是偶发：那一行**正好填满 88 字**，硬切分支必然走到。
历史推送里同类残句共 20 处。

## 本文件锁住什么

① 硬切后，续行行首**不得**是数字、小数点或单位（%，亿，万，点，家…）
② 优先退到最近的**空格** —— 本系统的空格只出现在数字/段名两侧，
   是天然词边界，退到那里最自然（比逐字退更可读）
③ 反面控制：把修复退回去（只留 `isdigit()` 守卫），用例必须变红
④ 不得因为加了这条守卫就把行切得过短（每条续行至少要有实质内容）
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "src"))

import analyze as A

_ok = 0

# 续行**绝不能以这些开头** —— 标点与光秃秃的单位。
#
# ⚠️ 口径只收标点，**不收数字**：`、` 是并列分隔点，按它断开后下一项
# 本来就该以数字开头（`…跌 1.88%、⏎ 2.58%，印制电路板…`），读者能读懂。
# 真正的残句是「一行以标点开头」——`%，为各指数中最远` 这一句就是用户
# 报的那个「怎么乱了呀」。
# 与 `analyze._NOWRAP_HEAD` 同源维护（这里再写一份是为了让测试能独立判断
# "实现是否真的守住了"，而不是拿实现自己的常量给自己打分）。
_BAD_HEAD = set('%.％‰,，、。；;）)】」》"')


def check(cond, msg):
    global _ok
    if cond:
        _ok += 1
    else:
        print(f"  ❌ {msg}")
        sys.exit(1)


# ---------- 生产真实样本 ①：触发缺陷的那一行 ----------
_LINE1 = ("**关键位** 上证距 20 日高 -3.75%，距 20 日低 3476.65 +2.66%；"
          "沪深300 距 20 日低 +2.49%；科创50 距 20 日低 +12.35%，为各指数"
          "中最远；创业板指距 20 日高 -12.19%；恒生指数距 20 日低 +2.20%；"
          "恒生科技距 20 日低 +3.64%，上方触发线 4243.65（距现价 +20.59%），"
          "下方 3395.38。")

_out = A._split_wall_lines(_LINE1)
_rows = _out.split("\n")
check(len(_rows) > 1,
      "这一行超过 88 字，必须被拆成多行（否则测不到硬切分支）")
for _ln in _rows[1:]:
    _head = _ln.strip()[:1]
    check(_head not in _BAD_HEAD,
          f"续行行首是 {_head!r} —— 数字/单位被劈到了行首：{_ln[:40]!r}")
# 具体盯住那次事故的形态：「%，」绝不能出现在行首
check(not any(_ln.strip().startswith("%") for _ln in _rows),
      "仍有续行以「%」开头 —— 这正是用户看到的那句残句")

# ---------- 生产真实样本 ②：同类风险（亿 / 家 / 日） ----------
for _name, _ln in (
    ("资金段", "**资金** 主力资金全面净流入：上证 +86.54 亿（占成交额 +2.8%）、"
               "沪深300 +78.71 亿（+3.9%）、创业板指 +67.72 亿（+3.4%）、"
               "科创50 +23.39 亿（+5.4%，占比最高）、北向 +12.3 亿，"
               "两融余额增加 45.6 亿至 1.87 万亿。"),
    ("盘面段", "**盘面** 六大指数全部上涨：科创50 +3.61%、创业板指 +2.84% 领涨，"
               "上证 +0.85%、沪深300 +0.84%、恒生指数 +0.44%、恒生科技 +0.31%。"
               "创业板指上涨 1313 家、下跌 83 家，科创50 上涨 41 家、下跌 9 家，"
               "成长板块近乎全线上行；沪深300 上涨 142 家、下跌 143 家。"),
):
    _o = A._split_wall_lines(_ln)
    for _l in _o.split("\n")[1:]:
        _h = _l.strip()[:1]
        check(_h not in _BAD_HEAD,
              f"[{_name}] 续行行首是 {_h!r}：{_l[:40]!r}")

# ---------- ②b 安全闸：切点落在标点前一位时必须退 ----------
# ⚠️ 这条防的是「空格回退/标点断句都帮不上」的形态：切点正好落在 `%` 前，
# 窗口内既没有空格可退、也没有 `、，` 可断（价格与单位是连写的）。
# 删掉安全闸后这里会切出以 `%` 开头的续行 —— 实测确认过。
_head = "**触发** "
_prefix = ("半导体主力净流出1583万占成交额-8.0%双破8%异动线两者分别跌1.88%和"
           "2.58%价跌钱走买盘缺席全天外流未见回补")
_t = _head + _prefix + "主" * 20 + "%" + "尾巴"
_rows2 = A._split_wall_lines(_t).split("\n")
check(len(_rows2) > 1, "该输入应被拆成多行")
for _ln in _rows2[1:]:
    _h = _ln.strip()[:1]
    check(_h not in _BAD_HEAD,
          f"安全闸失效：续行以 {_h!r} 开头（切点落在标点前一位却没退）："
          f"{_ln[:30]!r}")

# ---------- ③行宽仍然受控 ----------
check(all(len(_l) <= 92 for _l in _rows),
      f"拆完仍有行超过 92 字：{[len(x) for x in _rows]}")
for _ln in _rows[1:]:
    # 续行必须有实质内容，不能为了"退到空格"把行切得只剩几个字
    check(len(_ln.strip()) >= 8,
          f"续行过短（{len(_ln.strip())} 字），拆行退化：{_ln!r}")
    check(len(_ln) <= 92, f"续行超过 92 字：{len(_ln)}")

# ---------- ④短行不该被动 ----------
_SHORT = "**触发** 本轮没有触发任何阈值。"
check(A._split_wall_lines(_SHORT) == _SHORT,
      "短行被无谓改写了 —— 拆行只该动超限的行")

# ---------- ⑤接线断言：守卫必须真的写在代码里 ----------
_src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "..", "src", "analyze.py"), encoding="utf-8").read()
check("_NOWRAP_HEAD" in _src,
      "缺少 `_NOWRAP_HEAD` 常量 —— 行首禁用字符集不见了")
check('_p.rfind(" ",' in _src,
      "硬切没有优先退到最近的空格 —— 可读性会明显变差"
      "（本系统的空格正是天然词边界）")

print(f"ALL PASS (硬切不劈开数字与单位 {_ok} 个断言)")
